// Turns data/people.json into supabase/seed.sql: one row per person with their
// id and (lowercased) email. Re-run and re-apply whenever emails change; it is
// an upsert, so existing bios/photos/claims are untouched.
// Run: npm run data:seed-sql

import { readFileSync, writeFileSync } from "node:fs";

const people = JSON.parse(readFileSync(new URL("../data/people.json", import.meta.url), "utf8"));

const lit = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const rows = people.map((p) => `  (${lit(p.id)}, ${lit(p.email ? p.email.trim().toLowerCase() : null)})`);
const missing = people.filter((p) => !p.email).map((p) => p.id);

const sql = `-- Generated by scripts/seed-people-sql.mjs from data/people.json. Do not edit by hand.
-- Apply after supabase/migrations/20260917000000_people.sql, in the SQL editor.
insert into public.people (id, email) values
${rows.join(",\n")}
on conflict (id) do update set email = excluded.email;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`wrote supabase/seed.sql with ${people.length} people`);
if (missing.length) console.warn(`warn: ${missing.length} people have no email yet and cannot claim a profile: ${missing.join(", ")}`);
